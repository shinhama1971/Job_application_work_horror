// ============================================================================
// ファイルの役割: 外の森の空（何も描かれていない背景）に、地面や木と同じ霧を重ねている。
// 主な技術: 頂点バッファを使わない画面全体の三角形、射影行列とビュー行列からの視線の向きの復元、深度1.0での描画
//
// 霧（horrorMist.hlsli の床の近くの霧と、部屋全体に漂う薄い霧）は、面を描くピクセルシェーダーの中で、
// 目からその面までの視線に沿って足している。空には面がないので霧が足されず、遠くの地面の灰色の霧と黒い空の間に、
// 地平線のような1本の線が見えていた。
// ここでは、空の画素を「視線の先、描画の奥の端（1000）にある面」とみなし、地面と同じ式で霧を重ねている。
// 深度は1.0で、深度の書き込みはしないので、手前に何か描かれた画素は上書きしない。
// ============================================================================

#pragma once

#include "Object.h"

class SkyBackdrop final : public Object
{
public:
    void Init() override;
    void Update() override {}
    void Draw(Camera* camera) override;
    void Uninit() override {}

    // 監視カメラなどの別の視点には描かない
    bool DrawsInAuxiliaryView() const override { return false; }
};
