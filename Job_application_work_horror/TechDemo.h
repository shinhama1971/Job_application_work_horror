// ============================================================================
// ファイルの役割: 描画の技術を、その場で切り替えて見比べる「技術デモ」。
//                 F2で開き、↑↓で項目を選び、←→で方式を切り替えている。開いている間は画面の左に、
//                 項目の一覧・今の方式・説明・GPU時間を表示している。
// 主な技術: 描画の方式の切り替え（タイルベースライティング、深度プリパス、水面の反射、PCSS、自動露出、
//           水面の光の揺らぎ）、GPU時間の表示（タイムスタンプのクエリを平均）
//
// ・同じ場所・同じ視点のまま方式だけを変えられるので、見た目と処理の重さの違いを結果で比べられる。
// ・開いている間は、方向キーで視点が回らないようにしている（マウスとコントローラーの視点操作はそのまま）。
// ・閉じると、すべて普段の方式に戻している。
// ============================================================================

#pragma once

class GpuTimer;

namespace Effect
{
    class PostProcess;
}

namespace Tools::TechDemo
{
    // 表示用のHUDを作る・解放する
    void Init();
    void Uninit();

    // F2と方向キーを読み、選んだ方式を画面効果（自動露出）とデバッグ表示に反映している。
    // Debug構成ではデバッグ画面の値で毎フレーム上書きされるため、Debug::UI::ApplyTuning の後に呼ぶ。
    void Update(Effect::PostProcess& postProcess);

    // 技術デモを開いているか
    bool IsActive();

    // 描画で使う、今の方式（閉じているときは、すべて普段の方式を返している）
    // 本描画で、タイルごとに絞った光源のリストを使うか（falseなら全部の光源を画素ごとに計算する）
    bool UsesTiledLighting();
    // 本描画の前に、深度プリパスを描くか
    bool UsesDepthPrepass();
    // 水面の反射を描いて床に映すか
    bool UsesPlanarReflection();
    // 懐中電灯の影の方式（0=影なし、1=硬い影、2=PCSSの柔らかい影）
    int GetShadowMode();
    // 水面の光の揺らぎの強さに掛ける倍率（0なら出さない）
    float GetWaterCausticsScale();

    // 開いているときだけ、操作パネルを描いている（HUDより後、デバッグ画面より前に呼ぶ）
    void Draw(const GpuTimer& gpuTimer);
}
